# stm32/export_agent.py : turn a trained agent into a C header for the STM32 firmware
# ---------------------------------------------------------------
# Usage (from the project folder):
#     .\run stm32\export_agent.py cs1 improved_v4n2_seed0
#
# Writes stm32/firmware/Inc/agent_params.h with everything the C code needs:
#   - the network weights (2 hidden layers of 64, tanh) and the input scaling (VecNormalize)
#   - the gain ranges of the agent's version
#   - the case study's settings (sample time, limits, setpoints) and its process model
#   - the step-test results Python measured, so the board can print them next to its own
# Only first-order processes y[k+1] = A*y[k] + B*u[k-d] (CS1, CS2) can be exported to C.
# ---------------------------------------------------------------
import os, pickle, sys
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)                       # so "cases" and "core" can be imported
from stable_baselines3 import PPO
from cases import load_case
from core.tools import load_agent, run_test, score, completed, runs_folder, version_of
from core.versions import VERSIONS, gain_ranges

OUT = os.path.join(ROOT, "stm32", "firmware", "Inc", "agent_params.h")


def c_array(name, values, ctype="float"):
    """A numpy array as a C array definition (float32 values written so they read back exactly)."""
    values = np.asarray(values)
    suffix = "f" if ctype == "float" else ""
    fmt = (lambda v: f"{np.float32(v).item()!r}{suffix}") if ctype == "float" else (lambda v: repr(float(v)))
    if values.ndim == 1:
        body = ", ".join(fmt(v) for v in values)
        return f"static const {ctype} {name}[{len(values)}] = {{{body}}};\n"
    rows = ",\n    ".join("{" + ", ".join(fmt(v) for v in row) + "}" for row in values)
    return f"static const {ctype} {name}[{values.shape[0]}][{values.shape[1]}] = {{\n    {rows}\n}};\n"


def export(case_id, agent_name):
    case = load_case(case_id)
    folder = os.path.join(runs_folder(case_id), agent_name)
    version = version_of(agent_name)
    model = PPO.load(os.path.join(folder, "model"))
    with open(os.path.join(folder, "vecnormalize.pkl"), "rb") as f:
        norm = pickle.load(f)                  # the saved input scaling (only its numbers are needed)

    # --- the network: mlp_extractor.policy_net = [Linear, Tanh, Linear, Tanh], then action_net ---
    net = model.policy.mlp_extractor.policy_net
    W1, B1 = net[0].weight.detach().numpy(), net[0].bias.detach().numpy()
    W2, B2 = net[2].weight.detach().numpy(), net[2].bias.detach().numpy()
    W3, B3 = model.policy.action_net.weight.detach().numpy(), model.policy.action_net.bias.detach().numpy()
    assert W1.shape[1] == 3 and W2.shape == (W1.shape[0], W1.shape[0]), "expected a 3 -> 64 -> 64 network"

    # --- the process: only first-order y[k+1] = A*y[k] + B*u[k-d] ---
    process = case.Process()
    if not hasattr(process, "A") or not hasattr(process, "B"):
        raise SystemExit("Only first-order processes (with A and B) can be exported to C.")
    delay = getattr(process, "d", 0)

    # --- what Python measures on the step test (printed by the board for comparison) ---
    env, _ = run_test(case, load_agent(case, agent_name), version)
    m = score(env)

    low, high = gain_ranges(version, case)
    h = []
    h.append(f"/* agent_params.h : GENERATED by stm32/export_agent.py - do not edit by hand.\n"
             f" * Agent: runs/{case_id}/{agent_name}   ({case.NAME})\n */\n")
    h.append("#ifndef AGENT_PARAMS_H\n#define AGENT_PARAMS_H\n\n")
    h.append(f'#define AGENT_NAME          "{case_id}/{agent_name}"\n')
    h.append(f'#define AGENT_CASE_NAME     "{case.NAME}"\n')
    h.append(f"#define AGENT_N_ACTIONS     {W3.shape[0]}\n")
    h.append(f"#define AGENT_HIDDEN        {W1.shape[0]}\n")
    h.append(f"#define AGENT_WEIGHT_B      {1 if VERSIONS[version].weight_b else 0}\n\n")
    h.append("/* case-study settings */\n")
    h.append(f"#define RLPID_DT             {case.DT!r}f\n")
    h.append(f"#define RLPID_DT_MS          {int(round(case.DT * 1000))}\n")
    h.append(f"#define RLPID_U_LIMIT        {float(case.U_LIMIT)!r}f\n")
    h.append(f"#define RLPID_Y_LIMIT        {float(case.Y_LIMIT)!r}f\n")
    h.append(f"#define RLPID_ACTION_REPEAT  {case.ACTION_REPEAT}\n")
    h.append(f"#define RLPID_WARMUP_STEPS   {case.WARMUP_STEPS}\n")
    h.append(f"#define RLPID_HOLD_STEPS     {case.HOLD_STEPS}\n")
    h.append(f"#define RLPID_START_SETPOINT {float(case.START_SETPOINT)!r}f\n")
    h.append(f"#define RLPID_TEST_SETPOINT  {float(case.TEST_SETPOINT)!r}f\n")
    h.append(f"#define RLPID_SETPOINT_MIN   {float(case.TRAIN_RANGE[0])!r}f\n")
    h.append(f"#define RLPID_SETPOINT_MAX   {float(case.TRAIN_RANGE[1])!r}f\n\n")
    h.append("/* process model: y[k+1] = PLANT_A * y[k] + PLANT_B * u[k - PLANT_DELAY] */\n")
    h.append(f"#define PLANT_A             {float(process.A)!r}f\n")
    h.append(f"#define PLANT_B             {float(process.B)!r}f\n")
    h.append(f"#define PLANT_DELAY         {delay}\n\n")
    h.append("/* step-test results measured in Python (for comparison on the board) */\n")
    h.append(f"#define EXPECTED_OVERSHOOT  {m[0]:.4f}f\n#define EXPECTED_SETTLING   {m[1]:.4f}f\n")
    h.append(f"#define EXPECTED_ISE        {m[2]:.6f}f\n#define EXPECTED_IAE        {m[3]:.6f}f\n")
    h.append(f"#define EXPECTED_COMPLETED  {1 if completed(env) else 0}\n\n")
    h.append("#ifdef RLPID_DEFINE_WEIGHTS   /* defined only in rl_pid.c: the arrays exist once */\n")
    h.append(c_array("OBS_MEAN", norm.obs_rms.mean, "double"))
    h.append(c_array("OBS_VAR", norm.obs_rms.var, "double"))
    h.append(f"static const double OBS_EPS = {float(norm.epsilon)!r};\n")
    h.append(f"static const double OBS_CLIP = {float(norm.clip_obs)!r};\n")
    h.append(c_array("GAIN_LOW", low))
    h.append(c_array("GAIN_HIGH", high))
    h.append(c_array("W1", W1) + c_array("B1", B1) + c_array("W2", W2) + c_array("B2", B2))
    h.append(c_array("W3", W3) + c_array("B3", B3))
    h.append("#endif\n\n#endif /* AGENT_PARAMS_H */\n")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("".join(h))
    print(f"Exported runs/{case_id}/{agent_name} -> {os.path.relpath(OUT, ROOT)}")
    print(f"  Python step test: overshoot {m[0]:.1f} %, settling {m[1]:.2f} s, ISE {m[2]:.3f}, IAE {m[3]:.3f}")
    return m


if __name__ == "__main__":
    export(sys.argv[1] if len(sys.argv) > 1 else "cs1",
           sys.argv[2] if len(sys.argv) > 2 else "improved_v4n2_seed0")
